//! Generates bridge-functions.ps1 (the `bridge` command for PowerShell 5.1+) and the profile line that loads it.
//! Port of `src/main/cli/functions.ts`; the not-running fallback starts Bridge.exe directly.
use std::io;
use std::path::{Path, PathBuf};

pub const FUNCTIONS_FILE: &str = "bridge-functions.ps1";

/// PowerShell single-quoted literal. PS also treats curly single quotes as quotes, so those are doubled too.
fn ps_single(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('\'');
    for c in s.chars() {
        out.push(c);
        if matches!(c, '\'' | '\u{2018}' | '\u{2019}' | '\u{201A}' | '\u{201B}') {
            out.push(c);
        }
    }
    out.push('\'');
    out
}

/// Escape for inside a PowerShell double-quoted string.
fn ps_double_body(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if matches!(c, '`' | '$' | '"' | '\u{201C}' | '\u{201D}' | '\u{201E}') {
            out.push('`');
        }
        out.push(c);
    }
    out
}

/// The script. `exe` = Bridge.exe; `pipe_short` = `bridge-<user>` (a full `\\.\pipe\…` path is shortened).
pub fn render_functions_ps1(exe: &str, pipe_short: &str) -> String {
    let prefix = "\\\\.\\pipe\\";
    let short = match pipe_short.get(..prefix.len()) {
        Some(p) if p.eq_ignore_ascii_case(prefix) => &pipe_short[prefix.len()..],
        _ => pipe_short,
    };
    let pipe_line = format!("    $pipeName = {}", ps_single(short));
    let exe_line = format!("    $bridgeExe = {}", ps_single(exe));
    // Plain string lines so PowerShell text stays exactly as written.
    let lines: Vec<&str> = vec![
        "# Generated by Bridge. Edits are overwritten.",
        "# Adds the `bridge` command: bridge, bridge start, bridge open <name>, bridge run <name>, bridge add <link or path>.",
        "",
        "function bridge {",
        &pipe_line,
        &exe_line,
        "    $argv = @($args | ForEach-Object { [string]$_ })",
        "    $json = ConvertTo-Json -InputObject @{ argv = $argv; cwd = [string]$PWD.ProviderPath } -Compress",
        "    $client = New-Object System.IO.Pipes.NamedPipeClientStream('.', $pipeName, [System.IO.Pipes.PipeDirection]::InOut)",
        "    try {",
        "        try {",
        "            $client.Connect(400)",
        "        } catch {",
        "            # Bridge is not running: start it with the same args (it handles them on startup).",
        "            # Every arg is double-quoted by hand because Start-Process in PowerShell 5.1 does not quote.",
        "            $quoted = @($argv | ForEach-Object {",
        r#"                '"' + (([string]$_ -replace '(\\*)"', '$1$1\"') -replace '(\\+)$', '$1$1') + '"'"#,
        "            })",
        "            try {",
        "                # PowerShell 5.1 rejects an empty -ArgumentList.",
        "                if ($quoted.Count -gt 0) {",
        "                    Start-Process -FilePath $bridgeExe -ArgumentList $quoted",
        "                } else {",
        "                    Start-Process -FilePath $bridgeExe",
        "                }",
        "                Write-Host 'Starting Bridge\u{2026}'",
        "            } catch {",
        "                Write-Host ('Bridge could not start: ' + $_.Exception.Message) -ForegroundColor Red",
        "            }",
        "            return",
        "        }",
        "        $utf8 = New-Object System.Text.UTF8Encoding($false)",
        "        $writer = New-Object System.IO.StreamWriter($client, $utf8)",
        "        $writer.Write($json)",
        "        $writer.Write([char]10)",
        "        $writer.Flush()",
        "        $reader = New-Object System.IO.StreamReader($client, $utf8)",
        "        $pending = $reader.ReadLineAsync()",
        "        if (-not $pending.Wait(30000) -or -not $pending.Result) {",
        "            Write-Host 'Bridge did not answer.' -ForegroundColor Red",
        "            return",
        "        }",
        "        $result = $pending.Result | ConvertFrom-Json",
        "        if ($result.ok) { Write-Host $result.message } else { Write-Host $result.message -ForegroundColor Red }",
        "    } finally {",
        "        $client.Dispose()",
        "    }",
        "}",
        "",
    ];
    lines.join("\r\n")
}

/// Writes `<home>/bridge-functions.ps1` as UTF-8 with BOM (PowerShell 5.1 needs the BOM for non-ASCII paths).
/// `script` is written as-is (`render_functions_ps1` already uses CRLF). Returns the file path.
pub fn write_functions_file(home: &Path, script: &str) -> io::Result<PathBuf> {
    std::fs::create_dir_all(home)?;
    let file = home.join(FUNCTIONS_FILE);
    let mut bytes = Vec::with_capacity(script.len() + 3);
    bytes.extend_from_slice(&[0xEF, 0xBB, 0xBF]);
    bytes.extend_from_slice(script.as_bytes());
    std::fs::write(&file, bytes)?;
    Ok(file)
}

fn trim_seps(s: &str) -> &str {
    s.trim_end_matches(['\\', '/'])
}

/// True when `home` is `%APPDATA%\Bridge` (case-insensitive, trailing separators ignored).
pub fn is_default_home(home: &Path, appdata: Option<&str>) -> bool {
    let Some(appdata) = appdata.filter(|a| !a.is_empty()) else { return false };
    let norm = |s: &str| trim_seps(&s.replace('/', "\\")).to_lowercase();
    norm(&home.to_string_lossy()) == format!("{}\\bridge", norm(appdata))
}

/// The one line the user adds to his PowerShell profile. Uses `$env:APPDATA` when home is the default.
pub fn profile_line(home: &Path, is_default_home: bool) -> String {
    if is_default_home {
        return format!(". \"$env:APPDATA\\Bridge\\{FUNCTIONS_FILE}\"");
    }
    let home = home.to_string_lossy();
    format!(". \"{}\\{FUNCTIONS_FILE}\"", ps_double_body(trim_seps(&home)))
}
