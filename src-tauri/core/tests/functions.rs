//! Port of tests/unit/functions.test.ts. The not-running fallback now starts Bridge.exe directly (no Electron, no
//! app dir, no ELECTRON_RUN_AS_NODE juggling).
use std::path::Path;

use bridge_core::functions::*;

const EXE: &str = "C:\\Users\\Pat O'Brien\\AppData\\Local\\Bridge\\Bridge.exe";

fn ps() -> String {
    render_functions_ps1(EXE, "bridge-pat.obrien")
}

#[test]
fn defines_the_bridge_function_with_the_header() {
    let ps = ps();
    assert!(ps.starts_with("# Generated by Bridge. Edits are overwritten.\r\n"));
    assert!(ps.contains("function bridge {"));
}

#[test]
fn uses_the_short_pipe_name_and_a_400_ms_connect_timeout() {
    let ps = ps();
    assert!(ps.contains("    $pipeName = 'bridge-pat.obrien'\r\n"));
    assert!(!ps.contains("\\\\.\\pipe\\"));
    assert!(ps.contains("Connect(400)"));
    // A full pipe path is shortened too.
    let full = render_functions_ps1(EXE, "\\\\.\\PIPE\\bridge-pat.obrien");
    assert_eq!(full, ps);
}

#[test]
fn escapes_single_quotes_in_paths_o_brien() {
    let ps = ps();
    assert!(ps.contains("    $bridgeExe = 'C:\\Users\\Pat O''Brien\\AppData\\Local\\Bridge\\Bridge.exe'\r\n"));
    assert!(!ps.contains("Pat O'Brien"));
    // PowerShell also treats curly single quotes as quotes.
    let curly = render_functions_ps1("C:\\a\u{2018}b\u{2019}c\u{201A}d\u{201B}e.exe", "p");
    assert!(curly.contains("'C:\\a\u{2018}\u{2018}b\u{2019}\u{2019}c\u{201A}\u{201A}d\u{201B}\u{201B}e.exe'"));
}

#[test]
fn starts_bridge_exe_directly_when_not_running() {
    let ps = ps();
    assert!(ps.contains("Start-Process -FilePath $bridgeExe -ArgumentList $quoted"));
    assert!(ps.contains(
        "                '\"' + (([string]$_ -replace '(\\\\*)\"', '$1$1\\\"') -replace '(\\\\+)$', '$1$1') + '\"'\r\n"
    ));
    assert!(ps.contains("Write-Host 'Starting Bridge\u{2026}'"));
    assert!(ps.contains("Write-Host ('Bridge could not start: ' + $_.Exception.Message) -ForegroundColor Red"));
    assert!(!ps.contains("ELECTRON_RUN_AS_NODE"));
    assert!(!ps.contains("$appDir"));
    assert!(!ps.contains("$electronExe"));
}

#[test]
fn waits_30_s_for_the_answer_and_shows_failures_in_red() {
    let ps = ps();
    assert!(ps.contains("$pending.Wait(30000)"));
    assert!(ps.contains("Write-Host 'Bridge did not answer.' -ForegroundColor Red"));
    assert!(ps.contains(
        "if ($result.ok) { Write-Host $result.message } else { Write-Host $result.message -ForegroundColor Red }"
    ));
}

#[test]
fn uses_crlf_line_endings_only() {
    let ps = ps();
    assert!(ps.ends_with("}\r\n"));
    assert_eq!(ps.matches('\n').count(), ps.matches("\r\n").count());
}

#[test]
fn uses_env_appdata_for_the_default_home() {
    let appdata = "C:\\Users\\me\\AppData\\Roaming";
    let home = format!("{appdata}\\Bridge");
    assert!(is_default_home(Path::new(&home), Some(appdata)));
    assert!(is_default_home(Path::new(&format!("{appdata}\\BRIDGE\\")), Some(appdata)));
    assert!(is_default_home(Path::new(&home), Some(&format!("{appdata}\\"))));
    assert!(!is_default_home(Path::new("D:\\tmp\\bridge-test"), Some(appdata)));
    assert!(!is_default_home(Path::new(&home), None));
    assert_eq!(profile_line(Path::new(&home), true), ". \"$env:APPDATA\\Bridge\\bridge-functions.ps1\"");
}

#[test]
fn uses_the_literal_path_for_other_homes() {
    assert_eq!(
        profile_line(Path::new("D:\\tmp\\bridge-test"), false),
        ". \"D:\\tmp\\bridge-test\\bridge-functions.ps1\""
    );
    assert_eq!(
        profile_line(Path::new("D:\\tmp\\bridge-test\\"), false),
        ". \"D:\\tmp\\bridge-test\\bridge-functions.ps1\""
    );
    assert_eq!(profile_line(Path::new("D:\\a$b"), false), ". \"D:\\a`$b\\bridge-functions.ps1\"");
    assert_eq!(
        profile_line(Path::new("D:\\q\"`\u{201C}\u{201D}\u{201E}"), false),
        ". \"D:\\q`\"``\u{0060}\u{201C}`\u{201D}`\u{201E}\\bridge-functions.ps1\""
    );
}

#[test]
fn writes_bridge_functions_ps1_with_a_utf8_bom_and_returns_the_path() {
    let dir = tempfile::tempdir().unwrap();
    let home = dir.path().join("home");
    let p = write_functions_file(&home, "function bridge { \"\u{e9}\" }").unwrap();
    assert_eq!(p, home.join(FUNCTIONS_FILE));
    assert_eq!(FUNCTIONS_FILE, "bridge-functions.ps1");
    let bytes = std::fs::read(&p).unwrap();
    assert_eq!(&bytes[..3], &[0xef, 0xbb, 0xbf]);
    assert_eq!(std::str::from_utf8(&bytes[3..]).unwrap(), "function bridge { \"\u{e9}\" }");
}

/// The generated script really parses in Windows PowerShell 5.1, and the not-running path reaches Start-Process
/// (no args included: PS 5.1 rejects an empty -ArgumentList, so the script must not pass one).
#[cfg(windows)]
#[test]
fn powershell_runs_the_not_running_fallback() {
    let dir = tempfile::tempdir().unwrap();
    let home = dir.path().join("home O'x");
    let pipe = format!("bridge-absent-{}", std::process::id());
    let script = render_functions_ps1("C:\\nope\\Bridge.exe", &pipe);
    let file = write_functions_file(&home, &script).unwrap();
    let lit = file.to_string_lossy().replace('\'', "''");
    let out = std::process::Command::new("powershell.exe")
        .args(["-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass", "-Command"])
        .arg(format!("$ProgressPreference='SilentlyContinue'; . '{lit}'; bridge 6>&1; bridge add 'C:\\x y\\' 'say \"hi\"' 6>&1"))
        .output()
        .expect("powershell.exe");
    let text = format!("{}{}", String::from_utf8_lossy(&out.stdout), String::from_utf8_lossy(&out.stderr));
    assert_eq!(text.matches("Bridge could not start: ").count(), 2, "{text}");
    assert!(!text.contains("ArgumentList"), "{text}");
}
